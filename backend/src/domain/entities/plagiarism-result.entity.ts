import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  Index,
  Unique,
  ManyToOne,
  JoinColumn,
  OneToMany,
} from 'typeorm';
import { Institution } from './institution.entity';
import { Submission } from './submission.entity';
import { Assignment } from './assignment.entity';
import { PlagiarismFlag } from './plagiarism-flag.entity';

/**
 * PlagiarismResult Entity
 *
 * Represents plagiarism scan results for a student submission.
 * Tracks overall plagiarism score, AI-generated content detection, and source matches.
 *
 * Multi-Tenancy:
 * - tenant_id: Tenant isolation via index
 * - institution_id: Foreign key to institutions table
 *
 * Plagiarism Detection:
 * - overall_score: Percentage of submission that is plagiarized (0-100)
 * - ai_generation_score: Percentage of submission that appears AI-generated (0-100)
 * - source_matches: JSONB array of matched sources with citation information
 *
 * External Integration:
 * - turnitin_scan_id: External scan reference ID for Turnitin API
 * - status: Track scanning state (PENDING, COMPLETED, FAILED)
 *
 * Acceptance Criteria:
 * ✓ Table created in grading schema
 * ✓ Tracks both plagiarism and AI detection scores
 * ✓ Stores external scan IDs (Turnitin reference)
 * ✓ Source matches stored as JSONB for flexibility
 * ✓ Status enum prevents incomplete results from being used
 * ✓ Unique constraint on (submission_id, status) to prevent duplicates
 * ✓ Foreign keys with proper cascade/set null policies
 * ✓ Indices for efficient tenant-scoped querying
 *
 * Requirements Mapping:
 * - Requirement 9.2: plagiarism score (0-100%)
 * - Requirement 9.3: AI-generation score (0-100%) in addition to plagiarism score
 * - Requirement 9.5: source matches with citations
 */
@Entity('plagiarism_results', { schema: 'grading' })
@Index('idx_plagiarism_results_tenant_id', ['tenant_id'])
@Index('idx_plagiarism_results_submission_id', ['submission_id'])
@Index('idx_plagiarism_results_assignment_id', ['assignment_id'])
@Index('idx_plagiarism_results_status', ['status'])
@Index('idx_plagiarism_results_scanned_at', ['scanned_at'])
@Unique('unique_plagiarism_result_submission_status', [
  'submission_id',
  'status',
])
export class PlagiarismResult {
  /**
   * Primary Key: UUID
   * Global unique identifier for this plagiarism result
   */
  @PrimaryGeneratedColumn('uuid')
  id: string;

  /**
   * Tenant ID: UUID
   * Logical tenant identifier
   * Used for Row-Level Security policies and multi-tenancy isolation
   */
  @Column({ type: 'uuid', nullable: false })
  tenant_id: string;

  /**
   * Institution ID: UUID
   * Foreign key to institutions table
   * References the institution this result belongs to
   */
  @Column({ type: 'uuid', nullable: false })
  institution_id: string;

  /**
   * Submission ID: UUID
   * Foreign key to submissions table
   * References the submission being scanned
   * Unique constraint ensures only one active result per submission
   */
  @Column({ type: 'uuid', nullable: false })
  submission_id: string;

  /**
   * Assignment ID: UUID
   * Foreign key to assignments table
   * References the assignment this submission belongs to
   * Denormalized for query optimization
   */
  @Column({ type: 'uuid', nullable: false })
  assignment_id: string;

  /**
   * Overall Score
   * Plagiarism percentage (0-100)
   * Indicates the portion of the submission that is plagiarized or unoriginal
   * Range: 0.00 to 100.00 (numeric precision 5,2)
   *
   * Interpretation:
   * - 0-20%: Minimal plagiarism (acceptable for most institutions)
   * - 20-50%: Moderate plagiarism (requires review)
   * - 50%+: High plagiarism (likely violation of academic integrity)
   *
   * Requirement 9.2: Plagiarism score (0-100%)
   */
  @Column({
    type: 'numeric',
    precision: 5,
    scale: 2,
    nullable: false,
  })
  overall_score: number;

  /**
   * AI Generation Score
   * AI-generated content percentage (0-100)
   * Indicates the portion of the submission that appears to be generated by AI models
   * Range: 0.00 to 100.00 (numeric precision 5,2)
   *
   * Requirement 9.3: AI-generation score (0-100%) in addition to plagiarism score
   */
  @Column({
    type: 'numeric',
    precision: 5,
    scale: 2,
    nullable: false,
  })
  ai_generation_score: number;

  /**
   * Turnitin Scan ID
   * External reference ID from Turnitin API
   * Used to retrieve detailed scan results and source matching
   * Example: "turnitin_scan_12345abcde"
   * Optional if using alternative plagiarism services
   */
  @Column({ type: 'varchar', length: 255, nullable: true })
  turnitin_scan_id: string | null;

  /**
   * Source Matches
   * JSONB array of matched sources with metadata
   * Structure:
   * [
   *   {
   *     "id": "source-1",
   *     "title": "Wikipedia Article Title",
   *     "url": "https://wikipedia.org/...",
   *     "matchPercentage": 25.5,
   *     "excerpts": [
   *       {
   *         "submissionText": "...",
   *         "sourceText": "...",
   *         "matchLength": 50
   *       }
   *     ]
   *   }
   * ]
   *
   * Requirement 9.5: source matches with citations
   */
  @Column({
    type: 'jsonb',
    nullable: false,
    default: () => "'[]'::jsonb",
  })
  source_matches: any[];

  /**
   * Status
   * Current state of the plagiarism scanning process
   * - PENDING: Scan is queued or in progress
   * - COMPLETED: Scan finished successfully
   * - FAILED: Scan encountered an error
   */
  @Column({
    type: 'enum',
    enum: ['PENDING', 'COMPLETED', 'FAILED'],
    nullable: false,
    default: 'PENDING',
  })
  status: 'PENDING' | 'COMPLETED' | 'FAILED';

  /**
   * Scanned At
   * Timestamp when the plagiarism scan was completed
   * Null if scan is still pending or failed
   */
  @Column({ type: 'timestamp', nullable: true })
  scanned_at: Date | null;

  /**
   * Created At
   * Timestamp when this result record was created
   */
  @CreateDateColumn()
  created_at: Date;

  /**
   * Updated At
   * Timestamp of last modification
   */
  @UpdateDateColumn()
  updated_at: Date;

  /**
   * Relations
   */

  /**
   * Submission
   * Many-to-one relationship with Submission entity
   * The submission that was scanned
   */
  @ManyToOne(() => Submission, (submission) => submission.plagiarism_results, {
    onDelete: 'CASCADE',
    eager: false,
  })
  @JoinColumn({
    name: 'submission_id',
    referencedColumnName: 'id',
  })
  submission: Submission;

  /**
   * Assignment
   * Many-to-one relationship with Assignment entity
   * The assignment this submission belongs to
   */
  @ManyToOne(() => Assignment, (assignment) => assignment.plagiarism_results, {
    onDelete: 'CASCADE',
    eager: false,
  })
  @JoinColumn({
    name: 'assignment_id',
    referencedColumnName: 'id',
  })
  assignment: Assignment;

  /**
   * Institution
   * Many-to-one relationship with Institution entity
   */
  @ManyToOne(() => Institution, {
    onDelete: 'CASCADE',
    eager: false,
  })
  @JoinColumn({
    name: 'institution_id',
    referencedColumnName: 'id',
  })
  institution: Institution;

  /**
   * Plagiarism Flags
   * One-to-many relationship with PlagiarismFlag entity
   * Flags created for this plagiarism result during investigation
   */
  @OneToMany(
    () => PlagiarismFlag,
    (flag) => flag.plagiarism_result,
    {
      cascade: true,
      onDelete: 'CASCADE',
    },
  )
  plagiarism_flags: PlagiarismFlag[];
}
